"""End-to-end integration test for the 3-node Live Kalman stack and ESP32 ingest.

Uses only the Python standard library so it runs identically on Linux and Windows
runners in GitHub Actions as well as on developer machines.

Verifies:
  1. Independent startup of controller, receiver, and sender processes with
     configs/local-impaired.json (fading + DC drift + burst noise + ONNX policy).
  2. HTTP /healthz readiness across Controller (:8080), Receiver (:8082), and
     Sender (:8081).
  3. gRPC NodeService discovery and HEALTH_STATE_READY status on all 3 nodes
     via `labctl`.
  4. Live Receiver -> Controller telemetry (/api/v1/state) and SSE event feed
     (/api/v1/events), confirming ONNX policy decisions are emitted after the
     12-frame metrics window fills.
  5. Go Sender live BPSK file transfer (POST /api/v1/transfers?name=hello.txt)
     through completion and Receiver /api/v1/media NDJSON delivery.
  6. (When --esp32-hosttest is supplied) Stopping the Go Sender and replaying
     binary protobuf TxFrames generated by examples/esp32/hosttest/lk_hosttest.c
     for both hello.txt and kalman.bmp to POST :8082/api/v1/frames, asserting
     HTTP 200 on every frame, CRC-32 validity, automatic media-type detection,
     and byte-for-byte SHA-256 payload reconstruction.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import http.client
import json
import os
from pathlib import Path
import socket
import subprocess
import sys
import tempfile
import threading
import time
import urllib.error
import urllib.request


PORTS = (55051, 55052, 55053, 8080, 8081, 8082)


def exe_name(base: str) -> str:
    return f"{base}.exe" if os.name == "nt" else base


def assert_ports_free() -> None:
    busy: list[int] = []
    for port in PORTS:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            sock.settimeout(0.2)
            if sock.connect_ex(("127.0.0.1", port)) == 0:
                busy.append(port)
    if busy:
        raise RuntimeError(
            f"Cannot start E2E stack; localhost ports already in use: {busy}. "
            "Run scripts/stop-all.ps1 first."
        )


def http_json(url: str, method: str = "GET", body: bytes | None = None, headers: dict[str, str] | None = None, timeout: float = 5.0):
    req = urllib.request.Request(url, data=body, method=method, headers=headers or {})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        raw = resp.read()
        return resp.status, json.loads(raw.decode("utf-8"))


def wait_until(desc: str, predicate, timeout: float = 20.0, interval: float = 0.25):
    deadline = time.monotonic() + timeout
    last_err: Exception | None = None
    while time.monotonic() < deadline:
        try:
            val = predicate()
            if val:
                return val
        except Exception as exc:  # noqa: BLE001
            last_err = exc
        time.sleep(interval)
    detail = f" (last error: {last_err})" if last_err else ""
    raise TimeoutError(f"Timed out waiting for {desc} after {timeout:.1f}s{detail}")


class MediaStreamCollector:
    """Background NDJSON reader for GET http://127.0.0.1:8082/api/v1/media."""

    def __init__(self, url: str = "http://127.0.0.1:8082/api/v1/media") -> None:
        self.url = url
        self.lock = threading.Lock()
        self.completed: dict[str, dict] = {}
        self._buffers: dict[str, bytearray] = {}
        self._stop = threading.Event()
        self._ready = threading.Event()
        self._error: Exception | None = None
        self._thread = threading.Thread(target=self._run, daemon=True)

    def start(self) -> None:
        self._thread.start()
        if not self._ready.wait(timeout=5.0):
            raise RuntimeError(f"Failed to connect to {self.url}: {self._error}")

    def stop(self) -> None:
        self._stop.set()

    def _run(self) -> None:
        try:
            req = urllib.request.Request(self.url, method="GET")
            with urllib.request.urlopen(req, timeout=30.0) as resp:
                self._ready.set()
                for raw_line in resp:
                    if self._stop.is_set():
                        return
                    line = raw_line.strip()
                    if not line:
                        continue
                    event = json.loads(line.decode("utf-8"))
                    media = event.get("media") or {}
                    tid = media.get("transfer_id", "")
                    chunk = base64.b64decode(event.get("data", "")) if event.get("data") else b""
                    with self.lock:
                        buf = self._buffers.setdefault(tid, bytearray())
                        buf.extend(chunk)
                        if event.get("end_of_stream"):
                            self.completed[tid] = {
                                "event": event,
                                "bytes": bytes(buf),
                                "file_name": media.get("file_name", ""),
                            }
        except Exception as exc:  # noqa: BLE001
            self._error = exc
            self._ready.set()

    def get_completed_by_id(self, transfer_id: str) -> dict | None:
        with self.lock:
            return self.completed.get(transfer_id)

    def get_completed_by_name(self, file_name: str, id_prefix: str = "") -> dict | None:
        with self.lock:
            for tid, item in self.completed.items():
                if item["file_name"] == file_name and tid.startswith(id_prefix):
                    return item
        return None


def read_sse_decision(url: str, timeout: float = 15.0) -> dict:
    """Reads SSE events from Controller /api/v1/events until a decision event arrives."""
    deadline = time.monotonic() + timeout
    req = urllib.request.Request(url, headers={"Accept": "text/event-stream"})
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        seen_metrics = 0
        while time.monotonic() < deadline:
            raw = resp.readline()
            if not raw:
                break
            line = raw.decode("utf-8", errors="replace").strip()
            if not line.startswith("data:"):
                continue
            payload = json.loads(line[len("data:"):].strip())
            if payload.get("metrics"):
                seen_metrics += 1
            if payload.get("kind") == "decision" and payload.get("decision"):
                return payload
            # Fallback if cooldown already fired right before subscribing:
            if seen_metrics >= 80:
                return payload
    raise TimeoutError("Did not receive expected SSE events from Controller /api/v1/events")


def stop_process(proc: subprocess.Popen | None) -> None:
    if proc is None or proc.poll() is not None:
        return
    proc.terminate()
    try:
        proc.wait(timeout=5.0)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait(timeout=5.0)


def main() -> int:
    parser = argparse.ArgumentParser(description="Run Live Kalman E2E stack & ESP32 verification.")
    parser.add_argument("--root", default=".", help="Repository root directory")
    parser.add_argument("--bin-dir", default="bin", help="Directory containing built Go binaries")
    parser.add_argument("--config", default="configs/local-impaired.json", help="Stack JSON config")
    parser.add_argument("--esp32-hosttest", default="", help="Optional path to compiled lk_hosttest binary")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    bin_dir = (root / args.bin_dir).resolve()
    config_path = (root / args.config).resolve()

    for name in ("controller", "receiver", "sender", "labctl"):
        binary = bin_dir / exe_name(name)
        if not binary.is_file():
            raise FileNotFoundError(f"Missing required binary: {binary}")

    assert_ports_free()

    procs: dict[str, subprocess.Popen] = {}
    log_files: dict[str, Path] = {}
    log_handles = []

    with tempfile.TemporaryDirectory(prefix="lk-e2e-") as tmp:
        tmp_dir = Path(tmp)
        try:
            print("[1/6] Starting 3-node stack (controller -> receiver -> sender)...")
            for role in ("controller", "receiver", "sender"):
                log_path = tmp_dir / f"{role}.log"
                fh = open(log_path, "w", encoding="utf-8")  # noqa: SIM115
                log_handles.append(fh)
                log_files[role] = log_path
                procs[role] = subprocess.Popen(
                    [str(bin_dir / exe_name(role)), "--config", str(config_path)],
                    cwd=str(root),
                    stdout=fh,
                    stderr=subprocess.STDOUT,
                )
                time.sleep(0.25)

            print("[2/6] Verifying HTTP /healthz on :8080, :8082, and :8081...")
            for name, url in (
                ("controller", "http://127.0.0.1:8080/healthz"),
                ("receiver", "http://127.0.0.1:8082/healthz"),
                ("sender", "http://127.0.0.1:8081/healthz"),
            ):
                status, body = wait_until(
                    f"{name} /healthz",
                    lambda u=url: http_json(u) if http_json(u)[1].get("status") == "ok" else None,
                    timeout=10.0,
                )
                assert status == 200 and body.get("status") == "ok", f"{name} unhealthy: {body}"

            print("[3/6] Verifying gRPC NodeService discovery & readiness via labctl...")

            def check_labctl():
                res = subprocess.run(
                    [
                        str(bin_dir / exe_name("labctl")),
                        "-tx", "127.0.0.1:55051",
                        "-rx", "127.0.0.1:55052",
                        "-controller", "127.0.0.1:55053",
                    ],
                    cwd=str(root),
                    capture_output=True,
                    text=True,
                    timeout=6.0,
                    check=True,
                )
                data = json.loads(res.stdout)
                statuses = data.get("statuses") or []
                if len(statuses) != 3:
                    return None
                if all(s.get("health") == 2 and s.get("active") for s in statuses):
                    return data
                return None

            lab_snapshot = wait_until("all 3 nodes HEALTH_STATE_READY & active", check_labctl, timeout=15.0)
            node_ids = sorted(n.get("node_id") for n in lab_snapshot["nodes"])
            assert node_ids == ["controller-1", "receiver-1", "sender-1"], f"Unexpected nodes: {node_ids}"
            print(f"      Verified gRPC nodes ready & streaming: {', '.join(node_ids)}")

            print("[4/6] Verifying Controller /api/v1/state & live ONNX SSE /api/v1/events...")
            sse_event = read_sse_decision("http://127.0.0.1:8080/api/v1/events", timeout=15.0)
            _, state = wait_until(
                "Controller /api/v1/state sequence >= 20",
                lambda: http_json("http://127.0.0.1:8080/api/v1/state")
                if (http_json("http://127.0.0.1:8080/api/v1/state")[1].get("local-impaired") or {}).get("sequence", 0) >= 20
                else None,
                timeout=12.0,
            )
            latest_seq = state["local-impaired"]["sequence"]
            decision_info = sse_event.get("decision") or {}
            print(
                f"      Controller tracking active (seq={latest_seq}, "
                f"sse_kind={sse_event.get('kind')}, policy={decision_info.get('policy', 'active')})"
            )

            print("[5/6] Verifying live BPSK file transfer via Sender HTTP API & Receiver NDJSON...")
            collector = MediaStreamCollector("http://127.0.0.1:8082/api/v1/media")
            collector.start()
            hello_bytes = (root / "examples" / "media" / "hello.txt").read_bytes()
            post_status, queued_transfer = http_json(
                "http://127.0.0.1:8081/api/v1/transfers?name=hello.txt",
                method="POST",
                body=hello_bytes,
                headers={"Content-Type": "text/plain; charset=utf-8"},
            )
            assert post_status == 202, f"Expected 202 Accepted, got {post_status}: {queued_transfer}"
            transfer_id = queued_transfer["transferId"]

            def transfer_finished():
                _, tf = http_json("http://127.0.0.1:8081/api/v1/transfers")
                for item in tf.get("recent") or []:
                    if item.get("transferId") == transfer_id and item.get("state") == "sent":
                        return item
                return None

            sent_item = wait_until(f"Sender transfer {transfer_id} state=sent", transfer_finished, timeout=15.0)
            rx_media = wait_until(
                f"Receiver media end_of_stream for {transfer_id}",
                lambda: collector.get_completed_by_id(transfer_id),
                timeout=10.0,
            )
            assert sent_item["sentBytes"] == len(hello_bytes), f"Sent byte mismatch: {sent_item}"
            assert rx_media["event"]["received_size"] == len(hello_bytes), f"Receiver size mismatch: {rx_media['event']}"
            print(f"      Go Sender BPSK transfer {transfer_id} delivered ({len(hello_bytes)} bytes)")

            if args.esp32_hosttest:
                hosttest_bin = Path(args.esp32_hosttest).resolve()
                if not hosttest_bin.is_file():
                    raise FileNotFoundError(f"ESP32 hosttest binary not found: {hosttest_bin}")

                print("[6/6] Stopping Go Sender & verifying ESP32 Nanopb HTTP frame ingest...")
                stop_process(procs["sender"])
                time.sleep(0.3)

                for rel_media, expected_type in (
                    ("examples/media/hello.txt", 2),   # MEDIA_TYPE_TEXT
                    ("examples/media/kalman.bmp", 3),  # MEDIA_TYPE_IMAGE
                ):
                    src_file = root / rel_media
                    src_bytes = src_file.read_bytes()
                    src_sha256 = hashlib.sha256(src_bytes).hexdigest()
                    frames_dir = tmp_dir / f"frames_{src_file.stem}"
                    frames_dir.mkdir(parents=True, exist_ok=True)

                    gen = subprocess.run(
                        [str(hosttest_bin), str(src_file), str(frames_dir), "0.0"],
                        cwd=str(root),
                        capture_output=True,
                        text=True,
                        check=True,
                    )
                    frame_files = sorted(frames_dir.glob("frame_*.bin"))
                    assert frame_files, f"No frames generated for {src_file}"

                    conn = http.client.HTTPConnection("127.0.0.1", 8082, timeout=10)
                    try:
                        for frame_path in frame_files:
                            conn.request(
                                "POST",
                                "/api/v1/frames",
                                body=frame_path.read_bytes(),
                                headers={"Content-Type": "application/x-protobuf"},
                            )
                            resp = conn.getresponse()
                            reply = resp.read()
                            if resp.status != 200 or len(reply) == 0:
                                raise RuntimeError(f"{frame_path.name}: HTTP {resp.status} {reply[:120]!r}")
                    finally:
                        conn.close()

                    completed = wait_until(
                        f"ESP32 reassembly for {src_file.name}",
                        lambda name=src_file.name: collector.get_completed_by_name(name, id_prefix="esp32-"),
                        timeout=10.0,
                    )
                    ev = completed["event"]
                    got_sha256 = hashlib.sha256(completed["bytes"]).hexdigest()
                    assert ev.get("checksum_valid") is True, f"CRC invalid for {src_file.name}: {ev}"
                    assert ev.get("message") == "complete", f"Unexpected message for {src_file.name}: {ev}"
                    assert ev.get("detected_type") == expected_type, f"Wrong detected_type for {src_file.name}: {ev}"
                    assert got_sha256 == src_sha256, f"SHA-256 mismatch for {src_file.name}: {got_sha256} != {src_sha256}"
                    print(f"      ESP32 {gen.stdout.strip()} -> HTTP 200 x {len(frame_files)}, CRC valid, SHA-256 exact")
            else:
                print("[6/6] Skipping ESP32 hosttest (--esp32-hosttest not provided)")

            collector.stop()
            print("E2E verification PASSED.")
            return 0
        except Exception as exc:
            print(f"\nE2E verification FAILED: {exc}", file=sys.stderr)
            for fh in log_handles:
                fh.flush()
            for role, path in log_files.items():
                if path.is_file():
                    tail = "\n".join(path.read_text(encoding="utf-8", errors="replace").splitlines()[-30:])
                    print(f"\n--- {role}.log (last 30 lines) ---\n{tail}", file=sys.stderr)
            return 1
        finally:
            for proc in reversed(list(procs.values())):
                stop_process(proc)
            for fh in log_handles:
                fh.close()


if __name__ == "__main__":
    raise SystemExit(main())
